let num1 = Number(prompt("Enter your first number: "));
let num2 = Number(prompt("Enter your second number: "));

// Sum
console.log(num1 + num2);

// Difference
console.log(num1 - num2);

// Product
console.log(num1 * num2);

// Division
console.log(num1 / num2);

// Remainder
console.log(num1 % num2);

// First number raised to the power of second number
console.log(num1 ** num2);